const decode = (b64) => new Uint8Array(Buffer.from(b64, 'base64'));
const encode = (bytes) => Buffer.from(bytes).toString('base64');

function withAlphaChecked(record, label) {
  assert.ok(record, `${label}: record present`);
  assert.equal(record.data.length, record.width * record.height * 4, `${label}: RGBA length`);
  for (let i = 3; i < record.data.length; i += 4) {
    if (record.data[i] !== 255) assert.fail(`${label}: alpha hole at byte ${i}`);
  }
}

test('committed module is a byte-stable generator run inside the byte budget', () => {
  const committed = fs.readFileSync(MODULE_PATH, 'utf8');
  const committedBytes = fs.statSync(MODULE_PATH).size;
  assert.ok(committed.startsWith('// GENERATED by scripts/moth-variants.mjs'), 'generated header');
  assert.ok(committed.includes('do not edit by hand'), 'do not edit warning');
  assert.ok(committed.includes(`Algorithm: ${ALGORITHM}`), 'algorithm version in header');
  assert.ok(committed.includes(`Byte budget: ${MODULE_BUDGET_BYTES} bytes`), 'byte budget in header');
  assert.ok(committedBytes < MODULE_BUDGET_BYTES, `module ${committedBytes} bytes under budget`);
  assert.ok(
    committed.includes(`this module: ${String(committedBytes).padStart(7, '0')} bytes`),
    'header states the true byte size',
  );

  const fresh = buildModule({});
  assert.equal(fresh.source, committed, 'committed module equals a fresh default generation');
  const again = buildModule({});
  assert.equal(again.source, fresh.source, 'generation is deterministic across runs');
  assert.deepEqual(MOTH_VARIANTS.kinds && Object.keys(MOTH_VARIANTS.kinds), KINDS);
});

