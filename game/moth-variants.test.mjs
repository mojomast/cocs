test('--only and --size keep unrelated kinds out and still produce valid variants', () => {
  const only = buildModule({ only: ['metal'], size: 32 });
  assert.deepEqual(Object.keys(only.data.kinds), ['metal'], '--only keeps other kinds out');
  assert.equal(only.summary.length, 1);
  assert.equal(only.data.sizes.albedo, 32);
  assert.equal(only.data.sizes.roughness, 16);
  fs.mkdirSync(TMP_DIR, { recursive: true });
  const target = path.join(TMP_DIR, 'metal-only.mjs');
  writeModuleAtomic(target, only.source);
  const written = fs.readFileSync(target, 'utf8');
  assert.equal(written, only.source, 'atomic write round-trips');
  assert.ok(Buffer.byteLength(written, 'utf8') < MODULE_BUDGET_BYTES);
  assert.throws(() => buildModule({ only: ['not_a_kind'], size: 32 }), /unknown kind/);
});
